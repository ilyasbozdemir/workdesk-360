import Database from "better-sqlite3";
import { readFileSync } from "node:fs";
import { SnapshotEngine } from "../src/core/engine.js";
import { SqliteDataSource } from "../src/sqlite/source.js";
import { SqliteSnapshotRepository } from "../src/sqlite/repository.js";
import { definition } from "../src/templates/piyasa-fiyat-arastirma/definition.js";
const db = new Database("demo.sqlite");
db.exec(readFileSync(new URL("../src/sqlite/schema.sql", import.meta.url), "utf8"));
db.prepare("INSERT OR REPLACE INTO global_settings VALUES (?, ?, ?, ?, ?, ?)").run("g1", "Örnek Belediyesi", "Ankara", null, "Ayşe Kaya", "Yetkili");
db.prepare("INSERT OR REPLACE INTO units (id, ad) VALUES (?, ?)").run("u1", "Fen İşleri Müdürlüğü");
db.prepare("INSERT OR REPLACE INTO documents (id, dosya_no, konu, tarih, birim_id) VALUES (?, ?, ?, ?, ?)").run("d1", "2026/125", "Bilgisayar Alımı", "2026-10-31", "u1");
db.prepare("INSERT OR REPLACE INTO items VALUES (?, ?, ?, ?, ?, ?)").run("k1", "d1", 1, "Dizüstü Bilgisayar", 3, "Adet");
db.prepare("INSERT OR REPLACE INTO commission VALUES (?, ?, ?, ?, ?)").run("c1", "d1", "Ali Demir", "Müdür", "Başkan");
db.prepare("INSERT OR REPLACE INTO offers VALUES (?, ?, ?, ?, ?)").run("t1", "d1", "Örnek Teknoloji", "k1", 15000);
const engine = new SnapshotEngine(new SqliteDataSource(db));
const repo = new SqliteSnapshotRepository(db);
const ctx = {globalId:"g1", documentId:"d1"};
const first = repo.buildAndSave(engine, definition, ctx);
db.prepare("UPDATE documents SET konu = ? WHERE id = ?").run("Güncel Bilgisayar Alımı", "d1");
const second = repo.buildAndSave(engine, definition, ctx, {"document.aciklama":"Komisyon değerlendirmesi eklendi."});
console.log(JSON.stringify({revision1:first,revision2:second,historyCount:repo.history("d1",definition.id).length},null,2));
db.close();
